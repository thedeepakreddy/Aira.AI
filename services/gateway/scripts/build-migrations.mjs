/**
 * Rebuilds migrations/ALL.sql from the numbered files.
 *
 * ALL.sql was a hand-kept copy of the other three, and it had already drifted:
 * the parts were updated and the concatenation still carried the old
 * instructions. A file that must be edited in two places is a file that will
 * disagree with itself, so this generates it and a test fails when it is stale.
 */

import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'migrations');

const HEADER = `-- Aira memory schema — all migrations, in order.
--
-- GENERATED by scripts/build-migrations.mjs. Edit the numbered files, not this
-- one, then run \`npm run migrations:build\`.
--
-- Apply it with \`npm run migrate\` from services/gateway, which also verifies
-- the result; \`npm run migrate:check\` reports whether it is applied without
-- changing anything. Pasting this file into the Supabase SQL editor does the
-- same job by hand.
--
-- Every statement is 'if not exists', so re-running it is safe.
`;

/** The numbered files, in the order their names give. */
export function parts() {
  return readdirSync(dir).filter((name) => /^\d+_.*\.sql$/.test(name)).sort();
}

export function build() {
  const rule = '-- ' + '─'.repeat(69);
  const sections = parts().map((name) =>
    `${rule}\n-- ${name}\n${rule}\n${readFileSync(join(dir, name), 'utf8').trim()}\n`);
  return `${HEADER}\n${sections.join('\n')}`;
}

// Only writes when run directly; the test imports `build` and compares.
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(dir, 'ALL.sql'), build());
  console.log(`ALL.sql rebuilt from ${parts().length} migrations: ${parts().join(', ')}`);
}
